import React, { useState } from 'react';
import { X, Bell, AlertTriangle, Check, ShieldAlert, Sparkles } from 'lucide-react';
import { AlertSubscription, SavedLocation } from '../../types';

interface AlertSubscriptionsModalProps {
  isOpen: boolean;
  onClose: () => void;
  subscriptions: AlertSubscription[];
  locations: SavedLocation[];
  onSave: (subs: AlertSubscription[]) => void;
  onTriggerTestNotification?: () => void;
}

export const AlertSubscriptionsModal: React.FC<AlertSubscriptionsModalProps> = ({
  isOpen,
  onClose,
  subscriptions,
  locations,
  onSave,
  onTriggerTestNotification,
}) => {
  const [localSubs, setLocalSubs] = useState<AlertSubscription[]>(subscriptions);
  const [savedSuccess, setSavedSuccess] = useState(false);

  if (!isOpen) return null;

  const handleUpdateThreshold = (
    subId: string,
    field: 'tempThreshold' | 'apparentTempThreshold' | 'rainThresholdMm',
    val: number
  ) => {
    setLocalSubs((prev) =>
      prev.map((s) => (s.id === subId ? { ...s, [field]: val } : s))
    );
  };

  const handleToggle = (subId: string) => {
    setLocalSubs((prev) =>
      prev.map((s) => (s.id === subId ? { ...s, enabled: !s.enabled } : s))
    );
  };

  const handleSaveAll = () => {
    onSave(localSubs);
    setSavedSuccess(true);
    setTimeout(() => {
      setSavedSuccess(false);
      onClose();
    }, 800);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-950/70 backdrop-blur-sm animate-fadeIn">
      <div className="w-full max-w-2xl bg-slate-900 border border-slate-700 rounded-2xl shadow-2xl flex flex-col max-h-[90vh] overflow-hidden">
        {/* Header */}
        <div className="px-5 py-4 bg-slate-850 border-b border-slate-700 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-amber-500/10 border border-amber-500/30 flex items-center justify-center text-amber-400">
              <Bell className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-semibold text-white text-base">Heat &amp; Rain Alert Subscriptions</h3>
              <p className="text-xs text-slate-400">Feature 9: In-app alerts when forecast crosses your thresholds</p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Mandatory Label Callout */}
        <div className="px-5 py-3 bg-amber-950/40 border-b border-amber-900/50 flex items-start gap-2.5 text-xs text-amber-200">
          <AlertTriangle className="w-4 h-4 shrink-0 text-amber-400 mt-0.5" />
          <div>
            <strong className="text-amber-300 font-semibold">User-Set Thresholds Notice:</strong> Notifications generated by these triggers are calculated strictly against your chosen values and live Open-Meteo forecasts. They are <strong>never official government or meteorological warnings</strong>. Always heed alerts from the IMD or NDMA.
          </div>
        </div>

        {/* Content list */}
        <div className="flex-1 overflow-y-auto p-5 space-y-5">
          {localSubs.map((sub) => {
            return (
              <div
                key={sub.id}
                className="p-4 rounded-xl bg-slate-800/80 border border-slate-700 space-y-4"
              >
                <div className="flex items-center justify-between">
                  <div>
                    <h4 className="font-semibold text-white text-sm">{sub.locationName}</h4>
                    <span className="text-xs text-slate-400">Monitoring real-time 48-hour forecast</span>
                  </div>
                  <label className="relative inline-flex items-center cursor-pointer">
                    <input
                      type="checkbox"
                      checked={sub.enabled}
                      onChange={() => handleToggle(sub.id)}
                      className="sr-only peer"
                    />
                    <div className="w-11 h-6 bg-slate-700 peer-focus:outline-none rounded-full peer peer-checked:after:translate-x-full peer-checked:after:border-white after:content-[''] after:absolute after:top-[2px] after:left-[2px] after:bg-white after:border-slate-300 after:border after:rounded-full after:h-5 after:w-5 after:transition-all peer-checked:bg-teal-600"></div>
                  </label>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 pt-1">
                  {/* Temp Threshold */}
                  <div className="space-y-1.5 bg-slate-900/70 p-3 rounded-lg border border-slate-800">
                    <div className="flex items-center justify-between text-xs">
                      <span className="text-slate-300 font-medium">Air Temp Limit:</span>
                      <span className="text-rose-400 font-bold">{sub.tempThreshold}°C</span>
                    </div>
                    <input
                      type="range"
                      min={32}
                      max={46}
                      step={1}
                      value={sub.tempThreshold}
                      onChange={(e) =>
                        handleUpdateThreshold(sub.id, 'tempThreshold', Number(e.target.value))
                      }
                      className="w-full accent-rose-500 h-1.5 bg-slate-700 rounded-lg cursor-pointer"
                    />
                    <span className="text-[11px] text-slate-500 block">Trigger when air temp &ge; {sub.tempThreshold}°C</span>
                  </div>

                  {/* Apparent Temp Threshold */}
                  <div className="space-y-1.5 bg-slate-900/70 p-3 rounded-lg border border-slate-800">
                    <div className="flex items-center justify-between text-xs">
                      <span className="text-slate-300 font-medium">Heat Index Limit:</span>
                      <span className="text-orange-400 font-bold">{sub.apparentTempThreshold}°C</span>
                    </div>
                    <input
                      type="range"
                      min={35}
                      max={50}
                      step={1}
                      value={sub.apparentTempThreshold}
                      onChange={(e) =>
                        handleUpdateThreshold(sub.id, 'apparentTempThreshold', Number(e.target.value))
                      }
                      className="w-full accent-orange-500 h-1.5 bg-slate-700 rounded-lg cursor-pointer"
                    />
                    <span className="text-[11px] text-slate-500 block">Feels-like &ge; {sub.apparentTempThreshold}°C</span>
                  </div>

                  {/* Rain Threshold */}
                  <div className="space-y-1.5 bg-slate-900/70 p-3 rounded-lg border border-slate-800">
                    <div className="flex items-center justify-between text-xs">
                      <span className="text-slate-300 font-medium">Daily Rain Limit:</span>
                      <span className="text-sky-400 font-bold">{sub.rainThresholdMm} mm</span>
                    </div>
                    <input
                      type="range"
                      min={10}
                      max={100}
                      step={5}
                      value={sub.rainThresholdMm}
                      onChange={(e) =>
                        handleUpdateThreshold(sub.id, 'rainThresholdMm', Number(e.target.value))
                      }
                      className="w-full accent-sky-500 h-1.5 bg-slate-700 rounded-lg cursor-pointer"
                    />
                    <span className="text-[11px] text-slate-500 block">Forecast rain &ge; {sub.rainThresholdMm} mm</span>
                  </div>
                </div>
              </div>
            );
          })}
        </div>

        {/* Footer */}
        <div className="px-5 py-4 bg-slate-850 border-t border-slate-700 flex flex-wrap items-center justify-between gap-3">
          {onTriggerTestNotification && (
            <button
              type="button"
              onClick={onTriggerTestNotification}
              className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 border border-slate-700 text-xs flex items-center gap-1.5 transition-colors"
            >
              <Sparkles className="w-3.5 h-3.5 text-teal-400" />
              <span>Test In-App Alert Trigger</span>
            </button>
          )}

          <div className="flex items-center gap-2 ml-auto">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 text-xs font-medium text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
            >
              Cancel
            </button>
            <button
              type="button"
              onClick={handleSaveAll}
              className="px-5 py-2 rounded-xl bg-teal-600 hover:bg-teal-500 text-white font-medium text-xs flex items-center gap-1.5 transition-colors shadow-md shadow-teal-900/30"
            >
              {savedSuccess ? <Check className="w-4 h-4 text-white" /> : <Bell className="w-4 h-4" />}
              <span>{savedSuccess ? 'Saved!' : 'Save Thresholds'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
